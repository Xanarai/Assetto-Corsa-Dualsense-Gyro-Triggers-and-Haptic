def get_item_label(item: dict, lang: str = LANG_EN) -> str:
    """Returns the display name for a setting item."""
    return item.get("name_en", item.get("name", item.get("key", "")))


def get_item_info(item: dict, lang: str = LANG_EN) -> str:
    """Returns the explanation text for a setting item."""
    return item.get("info_en", item.get("info", ""))


def get_section_title(section_id: str, lang: str = LANG_EN) -> str:
    """Returns section header title."""
    for sec in CONFIG_SECTIONS:
        if sec["id"] == section_id:
            return sec.get("title_en", sec.get("title", section_id.capitalize()))
    return section_id.capitalize()
