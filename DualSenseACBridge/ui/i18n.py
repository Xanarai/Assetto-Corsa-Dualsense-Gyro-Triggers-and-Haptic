def t(key: str, lang: str = LANG_EN, **kwargs) -> str:
    """Retrieves localized string by key."""
    lang_dict = TEXTS.get(lang, TEXTS[LANG_EN])
    text = lang_dict.get(key, TEXTS[LANG_EN].get(key, key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


